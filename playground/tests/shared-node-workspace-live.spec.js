import {test,expect} from '@playwright/test';
const BASE='https://investment-n8n-native-editor-production.up.railway.app';
const FLOW='operations/WF01-latest-strategy-one.json';
const URL=BASE+'/?workflow='+encodeURIComponent(FLOW);
test('common node top actions: manual INPUT revision, real rerun, changed OUTPUT diff, persisted history',async ({page})=>{
  await page.goto(URL);
  await expect(page.locator('[data-testid="studio-node"]')).toHaveCount(16);
  const card=page.locator('[data-node-id="wf01-strategy-01"]');
  await card.hover();
  await page.getByTestId('node-run-wf01-strategy-01').click();
  await expect(page.getByTestId('shared-node-workspace')).toBeVisible();
  await expect(page.getByTestId('workspace-run-output')).toContainText('"max_pages": 3');
  await expect(page.getByTestId('workspace-run-status')).toContainText('SUCCESS');
  await expect(card.locator('.node-footer')).toContainText('Python 실행 성공');
  const current={ui_selection:'strategy',requested_detail_limit:1,max_pages:1};
  await page.getByTestId('workspace-input').fill(JSON.stringify(current,null,2));
  await page.getByTestId('workspace-save-run').click();
  await expect(page.getByTestId('workspace-run-output')).toContainText('"max_pages": 1');
  await expect(page.getByTestId('workspace-output-diff')).toContainText('max_pages');
  await expect(page.getByTestId('workspace-output-diff')).toContainText('이전: 3');
  await expect(page.getByTestId('workspace-output-diff')).toContainText('이번: 1');
  await expect(page.getByTestId('workspace-status')).toContainText('v1');
  await page.getByRole('button',{name:'노드 작업 공간 닫기'}).click();
  await page.reload();
  await card.hover();await page.getByTestId('node-open-wf01-strategy-01').click();
  await expect(page.getByTestId('workspace-input')).toHaveValue(/"max_pages": 1/);
  await expect(page.getByTestId('workspace-revision').locator('option')).toHaveCount(2);
  const saved=await (await page.context().request.get(BASE+'/api/studio/nodes/workspace?'+new URLSearchParams({workflow:FLOW,node_id:'wf01-strategy-01'}))).json();
  expect(saved.workspace.revision).toBe(1);
  expect(saved.workspace.input_json.max_pages).toBe(1);
  expect(saved.workspace.code_execution_approved).toBe(false);
  await page.screenshot({path:'test-results/shared-node-workspace-input-history.png',fullPage:true});
});
test('common module can version HTTP and Python drafts for any node but cannot execute them directly',async({page})=>{
  await page.goto(URL);
  const id='wf01-strategy-03';
  const card=page.locator('[data-node-id="'+id+'"]');
  await card.hover();
  await page.getByTestId('node-open-'+id).click();
  await expect(page.getByTestId('shared-node-workspace')).toBeVisible();
  await expect(page.getByTestId('workspace-save-run')).toBeDisabled();
  await page.getByTestId('workspace-execution-kind').selectOption('http');
  await page.getByTestId('workspace-api-url').fill('https://api.example.org/v2/catalog');
  await page.getByTestId('workspace-save').click();
  await expect(page.getByTestId('workspace-status')).toContainText('v1');
  await page.getByTestId('workspace-execution-kind').selectOption('python');
  await page.getByTestId('workspace-python-module').fill('adapter.collected');
  await page.getByTestId('workspace-python-function').fill('list_scripts');
  await page.getByTestId('workspace-python-code').fill('def list_scripts(x):\n    return x');
  await page.getByTestId('workspace-save').click();
  await expect(page.getByTestId('workspace-status')).toContainText('v2');
  await page.getByTestId('workspace-revision').selectOption('1');
  await page.getByTestId('workspace-restore').click();
  await expect(page.getByTestId('workspace-api-url')).toHaveValue('https://api.example.org/v2/catalog');
  await page.getByTestId('workspace-save').click();
  await expect(page.getByTestId('workspace-status')).toContainText('v3');
  const query=new URLSearchParams({workflow:FLOW,node_id:id});
  const history=await(await page.context().request.get(BASE+'/api/studio/nodes/workspace/revisions?'+query)).json();
  expect(history.revisions.map(x=>x.revision)).toEqual([3,2,1]);
  expect(history.revisions[1].execution_draft.python_code).toContain('return x');
  expect(history.revisions[0].execution_draft.api_url).toBe('https://api.example.org/v2/catalog');
  await expect(page.getByTestId('node-run-'+id)).toBeDisabled();
  await page.screenshot({path:'test-results/shared-node-workspace-code-draft-history.png',fullPage:true});
});
